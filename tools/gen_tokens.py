#!/usr/bin/env python3
"""Generate src/wa/tokens.c from a WhatsApp token dictionary JSON file.

The JSON format is the one used by whatsapp-rust (MIT licensed):
  {"single_byte": [...236 strings...], "double_byte": [[256], [256], [256], [256]]}

Usage: tools/gen_tokens.py path/to/tokens.json > src/wa/tokens_table.h
"""
import json
import sys


def c_str(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append('\\x%02x' % ord(ch))
    return '"' + ''.join(out) + '"'


def main():
    with open(sys.argv[1], encoding='utf-8') as f:
        d = json.load(f)
    single = d['single_byte']
    double = d['double_byte']
    assert len(single) <= 256 and len(double) == 4
    print('/* Generated by tools/gen_tokens.py - do not edit. */')
    print('/* Token dictionary for the WhatsApp binary XML format (version 3). */')
    print('#define WA_SINGLE_TOKEN_COUNT %d' % len(single))
    print('static const char *const wa_single_tokens[WA_SINGLE_TOKEN_COUNT] = {')
    for s in single:
        print('    %s,' % c_str(s))
    print('};')
    print('#define WA_DOUBLE_DICT_COUNT 4')
    print('static const char *const wa_double_tokens[4][256] = {')
    for block in double:
        assert len(block) == 256
        print('    {')
        for s in block:
            print('        %s,' % c_str(s))
        print('    },')
    print('};')


if __name__ == '__main__':
    main()
